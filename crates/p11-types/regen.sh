#!/bin/sh
# Regenerate src/generated.rs from the vendored OASIS PKCS#11 v3.2 headers.
# Needs bindgen-cli (cargo install bindgen-cli) and libclang; the result is
# committed, so normal builds need neither.
set -eu
cd "$(dirname "$0")"
bindgen vendor/wrapper.h --use-core --no-doc-comments \
	--allowlist-type 'CK_.*' --allowlist-var 'CK.*' \
	--default-macro-constant-type unsigned -- \
	| sed -E \
	  -e 's/^pub const (CK[A-Za-z0-9_]*): u32 = /pub const \1: CK_ULONG = /' \
	  -e 's/^pub const CK_UNAVAILABLE_INFORMATION: i32 = -1;/pub const CK_UNAVAILABLE_INFORMATION: CK_ULONG = !0;/' \
	  -e '/^pub const NULL_PTR/d' \
	> src/generated.rs

# names.rs: lookup tables of CKM_*, CKA_* and CKR_* constants
python3 - <<'PY'
import re
s = open('src/generated.rs').read()
def names(prefix):
    seen, out = set(), []
    for m in re.finditer(r'pub const (' + prefix + r'\w+): CK_ULONG = ', s):
        if m.group(1) not in seen:
            seen.add(m.group(1)); out.append(m.group(1))
    return out
def arr(name, items):
    return "pub(crate) static %s: &[(&str, CK_ULONG)] = &[\n" % name + ''.join('    ("%s", %s),\n' % (n, n) for n in items) + "];\n"
out = "// Generated by regen.sh from generated.rs: names of mechanisms, attributes and return values.\nuse crate::*;\n\n"
out += arr('MECHANISMS', names('CKM_')) + arr('ATTRIBUTES', names('CKA_')) + arr('RETURN_VALUES', names('CKR_'))
open('src/names.rs', 'w').write(out)
PY
