//! Wire messages: one request and one response structure per call, and the
//! `Request` / `Response` enums the transport layers pass around.

use crate::model::*;
use std::fmt::Write as _;

pub fn const_name(c: &Call) -> String {
    format!("CALL_{}", snake(c.short()).to_uppercase())
}

pub fn generate(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use crate::attr::*;").unwrap();
    writeln!(w, "use crate::codec::*;").unwrap();
    writeln!(w, "use crate::error::Result;").unwrap();
    writeln!(w, "use crate::secret::Secret;").unwrap();
    writeln!(w, "use crate::structs::*;").unwrap();
    writeln!(w, "use crate::tree::Node;\n").unwrap();

    writeln!(w, "/// Static facts about one call.").unwrap();
    writeln!(w, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(
        w,
        "pub struct CallInfo {{ pub id: u16, pub name: &'static str, pub since: &'static str, pub rw: bool, pub secret: bool }}\n"
    )
    .unwrap();
    writeln!(w, "pub static CALLS: [CallInfo; {}] = [", api.calls.len()).unwrap();
    for c in &api.calls {
        writeln!(
            w,
            "    CallInfo {{ id: {}, name: {:?}, since: {:?}, rw: {}, secret: {} }},",
            c.id,
            c.name,
            c.since.label(),
            c.rw,
            c.has_secret()
        )
        .unwrap();
    }
    writeln!(w, "];\n").unwrap();
    writeln!(w, "/// Look a call up by id.").unwrap();
    writeln!(
        w,
        "pub fn call_info(id: u16) -> Option<&'static CallInfo> {{ CALLS.get((id as usize).wrapping_sub(1)) }}\n"
    )
    .unwrap();

    for c in &api.calls {
        writeln!(w, "pub const {}: u16 = {};", const_name(c), c.id).unwrap();
    }
    writeln!(w).unwrap();

    for c in &api.calls {
        let short = c.short();
        // request
        write_struct(w, &format!("{short}Req"), c.req_fields().map(|(a, t)| (a.name.clone(), t)).collect());
        // response
        write_struct(w, &format!("{short}Resp"), c.resp_fields().into_iter().collect());
    }

    // enums
    for (en, suffix) in [("Request", "Req"), ("Response", "Resp")] {
        writeln!(w, "#[derive(Debug, Clone, PartialEq)]").unwrap();
        writeln!(w, "pub enum {en} {{").unwrap();
        for c in &api.calls {
            writeln!(w, "    {}({}{suffix}),", c.short(), c.short()).unwrap();
        }
        writeln!(w, "}}\n").unwrap();
        writeln!(w, "impl {en} {{").unwrap();
        writeln!(w, "    pub fn call_id(&self) -> u16 {{ match self {{").unwrap();
        for c in &api.calls {
            writeln!(w, "        {en}::{}(_) => {},", c.short(), c.id).unwrap();
        }
        writeln!(w, "    }} }}").unwrap();
        writeln!(w, "    pub fn encode_body(&self) -> Vec<u8> {{ let mut w = Writer::new(); match self {{").unwrap();
        for c in &api.calls {
            writeln!(w, "        {en}::{}(x) => x.encode(&mut w),", c.short()).unwrap();
        }
        writeln!(w, "    }} w.into_vec() }}").unwrap();
        let err = if en == "Request" { "RequestError" } else { "ResponseError" };
        writeln!(w, "    pub fn decode(call: u16, body: &[u8]) -> core::result::Result<{en}, {err}> {{ match call {{")
            .unwrap();
        for c in &api.calls {
            writeln!(w, "        {} => Ok({en}::{}(from_slice(body).map_err({err}::Malformed)?)),", c.id, c.short())
                .unwrap();
        }
        writeln!(w, "        _ => Err({err}::Unknown),").unwrap();
        writeln!(w, "    }} }}").unwrap();
        writeln!(w, "}}\n").unwrap();
    }
    s
}

fn sample_req(t: &str) -> &'static str {
    match t {
        "u64" => "0x0102_0304_0506_0708",
        "bool" => "true",
        "Vec<u8>" => "vec![1, 2, 3]",
        "Option<Vec<u8>>" => "Some(vec![4, 5, 6])",
        "Option<Secret>" => "Some(Secret::from(vec![4, 5, 6]))",
        "[u8; 32]" => "[0x41; 32]",
        "Mech" => "Mech { mechanism: 0x1087, param: Some(Node::L(vec![Node::U(1), Node::B(vec![9]), Node::Absent])) }",
        "Template" => "Seq(vec![Attr { ty: 0, val: AttrVal::Ulong(4) }, Attr { ty: 3, val: AttrVal::Bytes(vec![0x78]) }, Attr { ty: 0x4000_0211, val: AttrVal::Nested(vec![Attr { ty: 1, val: AttrVal::Bytes(vec![1]) }]) }, Attr { ty: 0x600, val: AttrVal::UlongArray(vec![1, 2]) }, Attr { ty: 0x161, val: AttrVal::Unavailable }])",
        "MsgParam" => "MsgParam { mechanism: 0x1087, phase: 2, param: Some(Node::L(vec![Node::U(1)])) }",
        "OutSpec" => "OutSpec::Capacity(64)",
        "Seq<Query>" => "Seq(vec![Query { ty: 0x11, slot: Slot::Length }, Query { ty: 0x100, slot: Slot::Capacity(8) }, Query { ty: 0x4000_0211, slot: Slot::Nested(vec![Query { ty: 3, slot: Slot::Capacity(4) }]) }])",
        "AsyncIn" => "AsyncIn { version: 1, value: OutSpec::Length }",
        other => panic!("no sample for request type {other}"),
    }
}

