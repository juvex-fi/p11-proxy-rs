/// One example request and response per call, with every field filled: the
/// input of the golden-vector tests and the fuzzers' seeds.
pub fn samples(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use super::*;").unwrap();
    writeln!(w, "use crate::attr::*;").unwrap();
    writeln!(w, "use crate::secret::Secret;").unwrap();
    writeln!(w, "use crate::structs::*;").unwrap();
    writeln!(w, "use crate::tree::Node;").unwrap();
    writeln!(w, "use crate::{{Seq, U64s}};\n").unwrap();
    writeln!(w, "/// One example request for every call, in call order.").unwrap();
    writeln!(w, "pub fn sample_requests() -> Vec<Request> {{\n    vec![").unwrap();
    for c in &api.calls {
        write!(w, "        Request::{s}({s}Req {{", s = c.short()).unwrap();
        for (a, t) in c.req_fields() {
            write!(w, " {}: {},", a.name, sample_req(t)).unwrap();
        }
        writeln!(w, " }}),").unwrap();
    }
    writeln!(w, "    ]\n}}\n").unwrap();
    writeln!(w, "/// One example response for every call, in call order.").unwrap();
    writeln!(w, "pub fn sample_responses() -> Vec<Response> {{\n    vec![").unwrap();
    for c in &api.calls {
        write!(w, "        Response::{s}({s}Resp {{", s = c.short()).unwrap();
        for (n, t) in c.resp_fields() {
            write!(w, " {n}: {},", sample_resp(t)).unwrap();
        }
        writeln!(w, " }}),").unwrap();
    }
    writeln!(w, "    ]\n}}").unwrap();
    s
}

fn write_struct(w: &mut String, name: &str, fields: Vec<(String, &'static str)>) {
    writeln!(w, "#[derive(Debug, Clone, PartialEq)]").unwrap();
    writeln!(w, "pub struct {name} {{").unwrap();
    for (n, t) in &fields {
        writeln!(w, "    pub {n}: {t},").unwrap();
    }
    writeln!(w, "}}").unwrap();
    if fields.is_empty() {
        writeln!(w, "impl Encode for {name} {{ fn encode(&self, _w: &mut Writer) {{}} }}").unwrap();
        writeln!(
            w,
            "impl Decode for {name} {{ fn decode(_r: &mut Reader<'_>) -> Result<Self> {{ Ok({name} {{}}) }} }}\n"
        )
        .unwrap();
        return;
    }
    writeln!(w, "impl Encode for {name} {{").unwrap();
    writeln!(w, "    fn encode(&self, w: &mut Writer) {{").unwrap();
    for (n, _) in &fields {
        writeln!(w, "        self.{n}.encode(w);").unwrap();
    }
    writeln!(w, "    }}\n}}").unwrap();
    writeln!(w, "impl Decode for {name} {{").unwrap();
    writeln!(w, "    fn decode(r: &mut Reader<'_>) -> Result<Self> {{").unwrap();
    writeln!(w, "        Ok({name} {{").unwrap();
    for (n, _) in &fields {
        writeln!(w, "            {n}: Decode::decode(r)?,").unwrap();
    }
    writeln!(w, "        }})\n    }}\n}}\n").unwrap();
}
