//! The client library's C entry points, and the function-list tables.

use crate::model::*;
use std::fmt::Write as _;

fn params(c: &Call) -> Vec<(String, &'static str)> {
    let mut v = Vec::new();
    for a in &c.args {
        for (suffix, ty) in a.kind.c_params() {
            v.push((format!("{}{}", a.name, suffix), *ty));
        }
    }
    v
}

fn has_required_body(c: &Call) -> bool {
    c.args.iter().any(|a| a.kind.resp_ty().is_some() && !matches!(a.kind, Kind::Mech | Kind::MsgParam))
}

pub fn generate(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use crate::rt;").unwrap();
    writeln!(w, "use p11_types::*;").unwrap();
    writeln!(w, "use p11_wire::calls::*;\n").unwrap();

    for c in &api.calls {
        if c.custom {
            continue;
        }
        let ps = params(c);
        let sig: Vec<String> = ps.iter().map(|(n, t)| format!("{n}: {t}")).collect();
        writeln!(w, "/// # Safety").unwrap();
        writeln!(w, "/// Called by the application under the PKCS#11 contract for `{}`.", c.name).unwrap();
        writeln!(w, "#[no_mangle]").unwrap();
        writeln!(w, "#[allow(non_snake_case, clippy::too_many_arguments)]").unwrap();
        writeln!(w, "pub unsafe extern \"C\" fn {}({}) -> CK_RV {{", c.name, sig.join(", ")).unwrap();
        writeln!(w, "    rt::guard(|| {{").unwrap();
        // output pointers must be present
        for a in &c.args {
            match a.kind {
                Kind::OU64
                | Kind::OObject
                | Kind::OSession
                | Kind::OInfo
                | Kind::OSlotInfo
                | Kind::OTokenInfo
                | Kind::OSessionInfo
                | Kind::OMechInfo
                | Kind::AsyncData => {
                    writeln!(w, "        if {}_ptr.is_null() {{ return Err(CKR_ARGUMENTS_BAD); }}", a.name).unwrap();
                }
                _ => {}
            }
        }
        writeln!(w, "        // SAFETY: the application passes pointers as the PKCS#11 contract requires.").unwrap();
        writeln!(w, "        let req = {}Req {{", c.short()).unwrap();
        for a in &c.args {
            let n = &a.name;
            let e = match a.kind {
                Kind::Slot | Kind::Session | Kind::Object | Kind::U64 => format!("{n} as u64"),
                Kind::Bool => format!("{n} != 0"),
                Kind::Bytes => format!("unsafe {{ rt::bytes({n}_ptr, {n}_len) }}?"),
                Kind::OptBytes => format!("unsafe {{ rt::opt_bytes({n}_ptr, {n}_len) }}?"),
                Kind::Secret => format!("unsafe {{ rt::opt_secret({n}_ptr, {n}_len) }}?"),
                Kind::Label => format!("unsafe {{ rt::label({n}_ptr) }}?"),
                Kind::CStr => format!("unsafe {{ rt::cstr({n}_ptr) }}?"),
                Kind::Mech => format!("unsafe {{ p11_params::mech::capture_mech({n}_ptr) }}?"),
                Kind::Attrs => {
                    format!("p11_wire::Seq(unsafe {{ p11_params::attrs::capture_template({n}_ptr, {n}_len) }}?)")
                }
                Kind::MsgParam => {
                    let phase = if c.name.contains("Decrypt") {
                        "p11_wire::structs::MSG_DECRYPT"
                    } else {
                        "p11_wire::structs::MSG_ENCRYPT"
                    };
                    format!("unsafe {{ rt::msg_param(session as u64, {phase}, {n}_ptr, {n}_len) }}?")
                }
                Kind::OBytes => format!("unsafe {{ rt::out_spec({n}_ptr.cast(), {n}_len) }}?"),
                Kind::OU64s => format!("unsafe {{ rt::out_spec({n}_ptr.cast(), {n}_len) }}?"),
                Kind::OFixed => format!("rt::fixed_len({n}_ptr, {n}_len)?"),
                Kind::OHandles => format!("rt::handles_max({n}_ptr, {n}_max, {n}_count)?"),
                Kind::AttrsQuery => {
                    format!("p11_wire::Seq(unsafe {{ p11_params::attrs::capture_query({n}_ptr, {n}_len) }}?)")
                }
                Kind::AsyncData => format!("unsafe {{ rt::async_in({n}_ptr) }}"),
                _ => continue,
            };
            writeln!(w, "            {n}: {e},").unwrap();
        }
        writeln!(w, "        }};").unwrap();
        let is_msg_init = c.name.starts_with("C_Message") && c.name.ends_with("Init");
        if is_msg_init {
            writeln!(w, "        let mech_type = req.mechanism.mechanism;").unwrap();
        }
        writeln!(w, "        let (rv, resp) = rt::call(Request::{}(req), {})?;", c.short(), c.id).unwrap();
        writeln!(w, "        match resp {{").unwrap();
        writeln!(w, "            Some(Response::{}(r)) => {{", c.short()).unwrap();
        writeln!(w, "                let _ = &r;").unwrap();
        for a in &c.args {
            let n = &a.name;
            let e = match a.kind {
                Kind::Mech => format!("unsafe {{ p11_params::mech::apply_mech_out(&r.{n}_out, {n}_ptr, rv) }}?;"),
                Kind::MsgParam => {
                    format!("unsafe {{ p11_params::mech::apply_msg_out(&r.{n}_out, {n}_ptr, {n}_len, rv) }}?;")
                }
                Kind::OBytes => format!("unsafe {{ rt::apply_out_bytes(&r.{n}, {n}_ptr, {n}_len, rv) }}?;"),
                Kind::OFixed => format!("unsafe {{ rt::apply_fixed(&r.{n}, {n}_ptr, {n}_len, rv) }}?;"),
                Kind::OU64s => format!("unsafe {{ rt::apply_out_u64s(&r.{n}, {n}_ptr, {n}_len, rv) }}?;"),
                Kind::OHandles => format!("unsafe {{ rt::apply_handles(&r.{n}, {n}_ptr, {n}_max, {n}_count, rv) }}?;"),
                Kind::OU64 | Kind::OObject | Kind::OSession => {
                    format!("unsafe {{ rt::apply_u64(r.{n}, {n}_ptr, rv) }};")
                }
                Kind::OInfo => format!("unsafe {{ rt::apply_info(&r.{n}, {n}_ptr, rv) }};"),
                Kind::OSlotInfo => format!("unsafe {{ rt::apply_slot_info(&r.{n}, {n}_ptr, rv) }};"),
                Kind::OTokenInfo => format!("unsafe {{ rt::apply_token_info(&r.{n}, {n}_ptr, rv) }};"),
                Kind::OSessionInfo => format!("unsafe {{ rt::apply_session_info(&r.{n}, {n}_ptr, rv) }};"),
                Kind::OMechInfo => format!("unsafe {{ rt::apply_mech_info(&r.{n}, {n}_ptr, rv) }};"),
                Kind::AttrsQuery => format!("unsafe {{ rt::apply_query(&r.{n}, {n}_ptr, {n}_len, rv) }}?;"),
                Kind::AsyncData => format!("unsafe {{ rt::apply_async(&r.{n}, {n}_ptr, rv) }}?;"),
                _ => continue,
            };
            writeln!(w, "                {e}").unwrap();
        }
        writeln!(w, "            }}").unwrap();
        writeln!(w, "            Some(_) => return Err(CKR_DEVICE_ERROR),").unwrap();
        if has_required_body(c) {
            writeln!(w, "            None if rv == CKR_OK as u64 => return Err(CKR_DEVICE_ERROR),").unwrap();
        }
        writeln!(w, "            None => {{}}").unwrap();
        writeln!(w, "        }}").unwrap();
        if is_msg_init {
            writeln!(w, "        if rv == CKR_OK as u64 {{ rt::record_msg_mech(session as u64, mech_type); }}")
                .unwrap();
        }
        if c.name == "C_CloseSession" {
            writeln!(w, "        rt::forget_session(session as u64);").unwrap();
        }
        writeln!(w, "        Ok(rv as CK_RV)").unwrap();
        writeln!(w, "    }})").unwrap();
        writeln!(w, "}}\n").unwrap();
    }
    s
}

/// Function-list statics. `path` is where the entry points live.
pub fn tables(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use crate::exports::*;").unwrap();
    writeln!(w, "use crate::generated::*;").unwrap();
    writeln!(w, "use p11_types::*;\n").unwrap();
    writeln!(w, "/// The 2.40 function list.").unwrap();
    writeln!(w, "pub static LIST_2_40: CK_FUNCTION_LIST = CK_FUNCTION_LIST {{").unwrap();
    writeln!(w, "    version: CK_VERSION {{ major: 2, minor: 40 }},").unwrap();
    for c in api.calls.iter().filter(|c| c.since == Since::V2_40) {
        writeln!(w, "    {n}: Some({n}),", n = c.name).unwrap();
    }
    writeln!(w, "    C_GetFunctionList: Some(C_GetFunctionList),").unwrap();
    writeln!(w, "}};\n").unwrap();
    for (name, minor) in [("LIST_3_2", 2u8), ("LIST_3_1", 1), ("LIST_3_0", 0)] {
        writeln!(w, "pub static {name}: CK_FUNCTION_LIST_3_2 = CK_FUNCTION_LIST_3_2 {{").unwrap();
        writeln!(w, "    version: CK_VERSION {{ major: 3, minor: {minor} }},").unwrap();
        for c in &api.calls {
            writeln!(w, "    {n}: Some({n}),", n = c.name).unwrap();
        }
        writeln!(w, "    C_GetFunctionList: Some(C_GetFunctionList),").unwrap();
        writeln!(w, "    C_GetInterfaceList: Some(C_GetInterfaceList),").unwrap();
        writeln!(w, "    C_GetInterface: Some(C_GetInterface),").unwrap();
        writeln!(w, "}};\n").unwrap();
    }
    s
}
