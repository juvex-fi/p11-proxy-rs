//! The daemon's per-call translation: client handles to module handles on
//! the way in, module handles to client handles on the way out, plus the
//! policy checks that depend on what an argument is.

use crate::model::*;
use std::fmt::Write as _;

pub fn generate(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use p11_wire::calls::*;\n").unwrap();
    writeln!(w, "/// Translation and policy hooks the generated code calls. Errors are `CK_RV`s.").unwrap();
    writeln!(w, "pub trait Xlate {{").unwrap();
    writeln!(w, "    /// Client session handle to the module's.").unwrap();
    writeln!(w, "    fn session(&self, v: u64) -> Result<u64, u64>;").unwrap();
    writeln!(w, "    /// Client object handle to the module's (0 stays 0).").unwrap();
    writeln!(w, "    fn object(&self, v: u64, key: bool) -> Result<u64, u64>;").unwrap();
    writeln!(w, "    /// The module's object handle to the client's, registering it if new.").unwrap();
    writeln!(w, "    fn new_object(&self, real: u64) -> u64;").unwrap();
    writeln!(w, "    fn slot(&self, id: u64) -> Result<(), u64>;").unwrap();
    writeln!(w, "    fn mech_in(&self, m: &mut p11_wire::structs::Mech) -> Result<(), u64>;").unwrap();
    writeln!(w, "    fn attrs_in(&self, call: u16, a: &[p11_wire::attr::Attr]) -> Result<(), u64>;").unwrap();
    writeln!(w, "    /// `vsession` is the client's session handle, for the recorded message mechanism.").unwrap();
    writeln!(
        w,
        "    fn msg_in(&self, vsession: u64, phase: u8, p: &mut p11_wire::structs::MsgParam) -> Result<(), u64>;"
    )
    .unwrap();
    writeln!(w, "    fn params_out(&self, mechanism: u64, out: &mut Option<p11_wire::Node>);").unwrap();
    writeln!(w, "}}\n").unwrap();

    writeln!(w, "/// Rewrite a request for the module. The client's handles are replaced by the").unwrap();
    writeln!(w, "/// module's; anything the policy forbids is refused.").unwrap();
    writeln!(w, "#[allow(unused_variables)]").unwrap();
    writeln!(w, "pub fn xlate_request<X: Xlate + ?Sized>(x: &X, req: &mut Request) -> Result<(), u64> {{").unwrap();
    writeln!(w, "    match req {{").unwrap();
    for c in &api.calls {
        let has_session = c.args.iter().any(|a| a.kind == Kind::Session);
        let mut body = String::new();
        if has_session && c.args.iter().any(|a| a.kind == Kind::MsgParam) {
            writeln!(body, "            let vsession = r.session;").unwrap();
        }
        for a in &c.args {
            let n = &a.name;
            match a.kind {
                Kind::Session => writeln!(body, "            r.{n} = x.session(r.{n})?;").unwrap(),
                Kind::Object => writeln!(body, "            r.{n} = x.object(r.{n}, {})?;", n.contains("key")).unwrap(),
                Kind::Slot => writeln!(body, "            x.slot(r.{n})?;").unwrap(),
                Kind::Mech => writeln!(body, "            x.mech_in(&mut r.{n})?;").unwrap(),
                Kind::Attrs => writeln!(body, "            x.attrs_in({}, &r.{n}.0)?;", c.id).unwrap(),
                Kind::MsgParam => {
                    let phase = if c.name.contains("Decrypt") {
                        "p11_wire::structs::MSG_DECRYPT"
                    } else {
                        "p11_wire::structs::MSG_ENCRYPT"
                    };
                    writeln!(body, "            x.msg_in(vsession, {phase}, &mut r.{n})?;").unwrap()
                }
                _ => {}
            }
        }
        if body.is_empty() {
            continue;
        }
        // the message parameter must be checked against the client's session handle,
        // which is translated first; keep argument order otherwise
        writeln!(w, "        Request::{}(r) => {{\n{body}        }}", c.short()).unwrap();
    }
    writeln!(w, "        _ => {{}}").unwrap();
    writeln!(w, "    }}\n    Ok(())\n}}\n").unwrap();

    writeln!(w, "/// Rewrite the module's answer for the client (after a successful call).").unwrap();
    writeln!(w, "#[allow(unused_variables)]").unwrap();
    writeln!(w, "pub fn xlate_response<X: Xlate + ?Sized>(x: &X, req: &Request, resp: &mut Response) {{").unwrap();
    writeln!(w, "    match (req, resp) {{").unwrap();
    for c in &api.calls {
        let mut body = String::new();
        for a in &c.args {
            let n = &a.name;
            match a.kind {
                Kind::OObject => writeln!(body, "            r.{n} = x.new_object(r.{n});").unwrap(),
                Kind::OHandles => {
                    writeln!(body, "            for h in r.{n}.0.iter_mut() {{ *h = x.new_object(*h); }}").unwrap()
                }
                Kind::Mech => writeln!(body, "            x.params_out(q.{n}.mechanism, &mut r.{n}_out);").unwrap(),
                Kind::AsyncData => {
                    writeln!(body, "            if r.{n}.object != 0 {{ r.{n}.object = x.new_object(r.{n}.object); }}")
                        .unwrap();
                    writeln!(body, "            if r.{n}.additional_object != 0 {{ r.{n}.additional_object = x.new_object(r.{n}.additional_object); }}").unwrap();
                }
                _ => {}
            }
        }
        if body.is_empty() {
            continue;
        }
        writeln!(w, "        (Request::{s}(q), Response::{s}(r)) => {{\n{body}        }}", s = c.short()).unwrap();
    }
    writeln!(w, "        _ => {{}}").unwrap();
    writeln!(w, "    }}\n}}").unwrap();
    s
}
