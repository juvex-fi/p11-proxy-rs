//! The `Backend` trait, its dispatch function, and the dlopen implementation.

use crate::model::*;
use std::fmt::Write as _;

/// Trait with one method per call, and `dispatch` over the request enum.
pub fn trait_source(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use p11_wire::calls::*;").unwrap();
    writeln!(w, "use crate::Reply;\n").unwrap();
    writeln!(w, "/// A PKCS#11 provider: the real module, a mock, or anything else that can").unwrap();
    writeln!(w, "/// answer the calls. Every method defaults to `CKR_FUNCTION_NOT_SUPPORTED`.").unwrap();
    writeln!(w, "pub trait Backend: Send + Sync {{").unwrap();
    for c in &api.calls {
        writeln!(
            w,
            "    fn {}(&self, _r: &{}Req) -> Reply<{}Resp> {{ Reply::err(p11_types::CKR_FUNCTION_NOT_SUPPORTED) }}",
            c.method(),
            c.short(),
            c.short()
        )
        .unwrap();
    }
    writeln!(w, "    /// Run `call` on the address of the module's exported function `name`, under whatever lock")
        .unwrap();
    writeln!(w, "    /// the backend takes around module calls. Vendor-defined functions are not in the PKCS#11")
        .unwrap();
    writeln!(w, "    /// call table; a backend without them answers `CKR_FUNCTION_NOT_SUPPORTED`.").unwrap();
    writeln!(
        w,
        "    fn with_vendor_symbol(&self, _name: &str, _call: &mut dyn FnMut(usize) -> u64) -> Result<u64, u64> {{ Err(p11_types::CKR_FUNCTION_NOT_SUPPORTED as u64) }}"
    )
    .unwrap();
    writeln!(w, "}}\n").unwrap();
    writeln!(w, "/// Run one request against a backend.").unwrap();
    writeln!(w, "pub fn dispatch(b: &dyn Backend, req: &Request) -> (u64, Option<Response>) {{").unwrap();
    writeln!(w, "    match req {{").unwrap();
    for c in &api.calls {
        writeln!(
            w,
            "        Request::{s}(r) => {{ let x = b.{m}(r); (x.rv, x.resp.map(Response::{s})) }}",
            s = c.short(),
            m = c.method()
        )
        .unwrap();
    }
    writeln!(w, "    }}\n}}").unwrap();
    s
}

fn snake_field(c: &Call, a: &Arg) -> String {
    let _ = c;
    a.name.clone()
}

/// `Fns` (the module's function pointers) and `impl Backend for DlBackend`.
pub fn dl_source(api: &Api) -> String {
    let mut s = String::new();
    let w = &mut s;
    writeln!(w, "// Generated by p11-idl from api.idl. Do not edit.").unwrap();
    writeln!(w, "use p11_types::*;").unwrap();
    writeln!(w, "use p11_wire::calls::*;").unwrap();
    writeln!(w, "use p11_wire::structs::*;").unwrap();
    writeln!(w, "use p11_wire::{{Seq, U64s}};").unwrap();
    writeln!(w, "use p11_params::{{attrs::*, conv, mech::*}};").unwrap();
    writeln!(w, "use crate::dlrt::{{self, Reply}};\n").unwrap();

    // Fns
    writeln!(w, "/// The module's entry points, normalised across 2.40, 3.0 and 3.2 function lists.").unwrap();
    writeln!(w, "#[derive(Clone, Copy, Default)]").unwrap();
    writeln!(w, "#[allow(non_snake_case)]").unwrap();
    writeln!(w, "pub struct Fns {{").unwrap();
    for c in &api.calls {
        writeln!(w, "    pub {}: CK_C_{},", c.name, c.short()).unwrap();
    }
    writeln!(w, "}}\n").unwrap();
    writeln!(w, "impl Fns {{").unwrap();
    for (fname, ty, max) in [
        ("from_v2_40", "CK_FUNCTION_LIST", Since::V2_40),
        ("from_v3_0", "CK_FUNCTION_LIST_3_0", Since::V3_0),
        ("from_v3_2", "CK_FUNCTION_LIST_3_2", Since::V3_2),
    ] {
        writeln!(w, "    pub fn {fname}(l: &{ty}) -> Fns {{").unwrap();
        writeln!(w, "        Fns {{").unwrap();
        for c in &api.calls {
            if c.since <= max {
                writeln!(w, "            {n}: l.{n},", n = c.name).unwrap();
            } else {
                writeln!(w, "            {n}: None,", n = c.name).unwrap();
            }
        }
        writeln!(w, "        }}\n    }}").unwrap();
    }
    writeln!(w, "}}\n").unwrap();

    writeln!(w, "impl crate::Backend for crate::DlBackend {{").unwrap();
    for c in &api.calls {
        dl_method(w, c);
    }
    writeln!(w, "    #[cfg(feature = \"vendor\")]").unwrap();
    writeln!(
        w,
        "    fn with_vendor_symbol(&self, name: &str, call: &mut dyn FnMut(usize) -> u64) -> Result<u64, u64> {{ self.vendor_symbol(name, call) }}"
    )
    .unwrap();
    writeln!(w, "}}").unwrap();
    s
}

fn dl_method(w: &mut String, c: &Call) {
    let short = c.short();
    writeln!(w, "    #[allow(unused_variables, unused_mut)]").unwrap();
    writeln!(w, "    fn {}(&self, r: &{short}Req) -> Reply<{short}Resp> {{", c.method()).unwrap();
    // Loading and unloading the module is not a plain call.
    if c.name == "C_Initialize" || c.name == "C_Finalize" {
        writeln!(w, "        self.{}(r)\n    }}", c.method().trim_start_matches("c_")).unwrap();
        return;
    }
    writeln!(w, "        let Some(f) = self.fns.{} else {{ return Reply::err(CKR_FUNCTION_NOT_SUPPORTED) }};", c.name)
        .unwrap();
    let mut args: Vec<String> = Vec::new();
    let mut post: Vec<(String, String)> = Vec::new(); // (response field, expression)
    for a in &c.args {
        let n = snake_field(c, a);
        match a.kind {
            Kind::Slot | Kind::Session | Kind::Object | Kind::U64 => args.push(format!("r.{n} as CK_ULONG")),
            Kind::Bool => args.push(format!("u8::from(r.{n})")),
            Kind::Bytes => {
                args.push(format!("r.{n}.as_ptr() as CK_BYTE_PTR"));
                args.push(format!("r.{n}.len() as CK_ULONG"));
            }
            Kind::OptBytes => {
                writeln!(w, "        let (p_{n}, l_{n}) = dlrt::opt_bytes(&r.{n});").unwrap();
                args.push(format!("p_{n}"));
                args.push(format!("l_{n}"));
            }
            Kind::Secret => {
                writeln!(w, "        let (p_{n}, l_{n}) = dlrt::opt_secret(&r.{n});").unwrap();
                args.push(format!("p_{n}"));
                args.push(format!("l_{n}"));
            }
            Kind::Label => args.push(format!("r.{n}.as_ptr() as CK_UTF8CHAR_PTR")),
            Kind::CStr => {
                writeln!(
                    w,
                    "        let Some(c_{n}) = dlrt::cstring(&r.{n}) else {{ return Reply::err(CKR_ARGUMENTS_BAD) }};"
                )
                .unwrap();
                args.push(format!("c_{n}.as_ptr() as CK_UTF8CHAR_PTR"));
            }
            Kind::Mech => {
                writeln!(w, "        let mut m_{n} = match MechBuf::build(&r.{n}) {{ Ok(m) => m, Err(rv) => return Reply::err(rv) }};").unwrap();
                args.push(format!("m_{n}.as_mut_ptr()"));
                post.push((format!("{n}_out"), format!("m_{n}.extract_out()")));
            }
            Kind::Attrs => {
                writeln!(w, "        let mut t_{n} = match AttrBuf::build(&r.{n}.0) {{ Ok(t) => t, Err(rv) => return Reply::err(rv) }};").unwrap();
                args.push(format!("t_{n}.as_mut_ptr()"));
                args.push(format!("t_{n}.len()"));
            }
            Kind::MsgParam => {
                writeln!(w, "        let mut mp_{n} = match MsgBuf::build(&r.{n}) {{ Ok(m) => m, Err(rv) => return Reply::err(rv) }};").unwrap();
                args.push(format!("mp_{n}.as_mut_ptr()"));
                args.push(format!("mp_{n}.len()"));
                post.push((format!("{n}_out"), format!("mp_{n}.extract_out()")));
            }
            Kind::OBytes => {
                writeln!(w, "        let mut o_{n} = dlrt::OutBuf::new(r.{n});").unwrap();
                args.push(format!("o_{n}.ptr()"));
                args.push(format!("o_{n}.len_ptr()"));
                post.push((n.clone(), format!("o_{n}.finish(rv)")));
            }
            Kind::OFixed => {
                writeln!(w, "        let Some(mut o_{n}) = dlrt::FixedBuf::new(r.{n}) else {{ return Reply::err(CKR_ARGUMENTS_BAD) }};").unwrap();
                args.push(format!("o_{n}.ptr()"));
                args.push(format!("o_{n}.len()"));
                post.push((n.clone(), format!("o_{n}.finish(rv)")));
            }
            Kind::OU64s => {
                writeln!(w, "        let mut o_{n} = dlrt::OutU64Buf::new(r.{n});").unwrap();
                args.push(format!("o_{n}.ptr()"));
                args.push(format!("o_{n}.len_ptr()"));
                post.push((n.clone(), format!("o_{n}.finish(rv)")));
            }
            Kind::OHandles => {
                writeln!(w, "        let mut o_{n} = dlrt::HandleBuf::new(r.{n});").unwrap();
                args.push(format!("o_{n}.ptr()"));
                args.push(format!("o_{n}.max()"));
                args.push(format!("o_{n}.count_ptr()"));
                post.push((n.clone(), format!("o_{n}.finish(rv)")));
            }
            Kind::OU64 | Kind::OObject | Kind::OSession => {
                writeln!(w, "        let mut v_{n}: CK_ULONG = 0;").unwrap();
                args.push(format!("&mut v_{n}"));
                post.push((n.clone(), format!("v_{n} as u64")));
            }
            Kind::OInfo | Kind::OSlotInfo | Kind::OTokenInfo | Kind::OSessionInfo | Kind::OMechInfo => {
                let (cty, conv) = match a.kind {
                    Kind::OInfo => ("CK_INFO", "info_to_wire"),
                    Kind::OSlotInfo => ("CK_SLOT_INFO", "slot_info_to_wire"),
                    Kind::OTokenInfo => ("CK_TOKEN_INFO", "token_info_to_wire"),
                    Kind::OSessionInfo => ("CK_SESSION_INFO", "session_info_to_wire"),
                    _ => ("CK_MECHANISM_INFO", "mech_info_to_wire"),
                };
                writeln!(w, "        // SAFETY: these are plain-data C structures; all zero is valid.").unwrap();
                writeln!(w, "        let mut v_{n}: {cty} = unsafe {{ core::mem::zeroed() }};").unwrap();
                args.push(format!("&mut v_{n}"));
                post.push((n.clone(), format!("conv::{conv}(&v_{n})")));
            }
            Kind::AttrsQuery => {
                writeln!(w, "        let mut q_{n} = match QueryBuf::build(&r.{n}.0) {{ Ok(q) => q, Err(rv) => return Reply::err(rv) }};").unwrap();
                args.push(format!("q_{n}.as_mut_ptr()"));
                args.push(format!("q_{n}.len()"));
                post.push((n.clone(), format!("Seq(q_{n}.finish())")));
            }
            Kind::AsyncData => {
                writeln!(w, "        let mut a_{n} = dlrt::AsyncBuf::new(&r.{n});").unwrap();
                args.push(format!("a_{n}.as_mut_ptr()"));
                post.push((n.clone(), format!("a_{n}.finish(rv)")));
            }
        }
    }
    // C parameters the proxy never uses (reserved pointers, callbacks).
    match c.name.as_str() {
        "C_WaitForSlotEvent" => args.push("core::ptr::null_mut()".into()),
        "C_OpenSession" => {
            args.insert(2, "core::ptr::null_mut()".into());
            args.insert(3, "None".into());
        }
        _ => {}
    }
    if c.name != "C_WaitForSlotEvent" {
        writeln!(w, "        let _g = self.guard();").unwrap();
    }
    writeln!(w, "        // SAFETY: every pointer passed is valid for the call: the buffers above are").unwrap();
    writeln!(w, "        // owned locals or arena memory that outlives it, sized as the module is told.").unwrap();
    writeln!(w, "        let rv = unsafe {{ f({}) }} as u64;", args.join(", ")).unwrap();
    if post.is_empty() {
        writeln!(w, "        Reply {{ rv, resp: None }}").unwrap();
    } else {
        writeln!(w, "        if !dlrt::wants_body(rv) {{ return Reply {{ rv, resp: None }}; }}").unwrap();
        writeln!(w, "        Reply {{ rv, resp: Some({short}Resp {{").unwrap();
        for (f, e) in &post {
            writeln!(w, "            {f}: {e},").unwrap();
        }
        writeln!(w, "        }}) }}").unwrap();
    }
    writeln!(w, "    }}").unwrap();
}
